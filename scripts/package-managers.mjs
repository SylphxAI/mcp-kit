// Renders a Homebrew formula and a Scoop manifest from a release's archives.
// Usage: node package-managers.mjs --name N --version V --repo owner/repo
//   --sums SHA256SUMS [--package-json F] [--description D] [--homepage H] [--license L]
//   [--formula-out Formula/N.rb] [--scoop-out bucket/N.json]
// Archives are the ones release.yml attaches: <name>-<key>.tar.gz, and
// <name>-win32-x64-msvc.zip for Windows. SHA256SUMS is `sha256sum` output.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { pathToFileURL } from "node:url";

const MAC_LINUX = [
  ["on_macos", "on_arm", "darwin-arm64"],
  ["on_macos", "on_intel", "darwin-x64"],
  ["on_linux", "on_arm", "linux-arm64-gnu"],
  ["on_linux", "on_intel", "linux-x64-gnu"],
];
const WIN_KEY = "win32-x64-msvc";

export function parseSums(text) {
  const sums = {};
  for (const line of text.split("\n")) {
    const m = line.match(/^([a-f0-9]{64}) [ *](.+)$/);
    if (m) sums[m[2].trim()] = m[1];
  }
  return sums;
}

function need(sums, file) {
  if (!sums[file]) throw new Error(`no SHA-256 for ${file}`);
  return sums[file];
}

const q = (s) => JSON.stringify(String(s));
const releaseUrl = (repo, version, file) => `https://github.com/${repo}/releases/download/v${version}/${file}`;

export function className(name) {
  return name.split(/[^A-Za-z0-9]+/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
}

export function formula({ name, version, repo, sums, description, homepage, license }) {
  let out = `# Generated by SylphxAI/mcp-kit release.yml for v${version}.\n`;
  out += `class ${className(name)} < Formula\n`;
  out += `  desc ${q(description)}\n  homepage ${q(homepage)}\n`;
  if (license) out += `  license ${q(license)}\n`;
  let os = "";
  for (const [o, arch, key] of MAC_LINUX) {
    const file = `${name}-${key}.tar.gz`;
    if (o !== os) {
      if (os) out += "  end\n";
      out += `\n  ${o} do\n`;
      os = o;
    } else out += "\n";
    out += `    ${arch} do\n      url ${q(releaseUrl(repo, version, file))}\n      sha256 ${q(need(sums, file))}\n    end\n`;
  }
  out += "  end\n";
  out += `\n  def install\n    bin.install ${q(name)}\n  end\n`;
  out += `\n  test do\n    assert_equal "${name} #{version}", shell_output("#{bin}/${name} version").strip\n  end\nend\n`;
  return out;
}

export function scoop({ name, version, repo, sums, description, homepage, license }) {
  const file = `${name}-${WIN_KEY}.zip`;
  const manifest = {
    version,
    description,
    homepage,
    ...(license ? { license } : {}),
    architecture: { "64bit": { url: releaseUrl(repo, version, file), hash: need(sums, file) } },
    bin: `${name}.exe`,
    checkver: { github: `https://github.com/${repo}` },
    autoupdate: { architecture: { "64bit": { url: releaseUrl(repo, "$version", file) } } },
  };
  return `${JSON.stringify(manifest, null, 4)}\n`;
}

function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

function main(argv) {
  const a = {};
  for (let i = 0; i < argv.length; i += 2) a[argv[i].replace(/^--/, "")] = argv[i + 1] ?? "";
  const pkg = a["package-json"] ? JSON.parse(readFileSync(a["package-json"], "utf8")) : {};
  const repo = a.repo;
  const meta = {
    name: a.name,
    version: a.version,
    repo,
    sums: parseSums(readFileSync(a.sums, "utf8")),
    description: a.description || pkg.description || `${a.name} MCP server`,
    homepage: a.homepage || (typeof pkg.homepage === "string" && pkg.homepage) || `https://github.com/${repo}`,
    license: a.license || (typeof pkg.license === "string" && pkg.license) || "",
  };
  if (!meta.name || !meta.version || !/^[^/]+\/[^/]+$/.test(repo ?? "")) throw new Error("--name, --version and --repo owner/repo are required");
  if (a["formula-out"]) write(a["formula-out"], formula(meta));
  if (a["scoop-out"]) write(a["scoop-out"], scoop(meta));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  try { main(process.argv.slice(2)); } catch (e) { console.error(`::error::${e.message}`); process.exit(1); }
}
